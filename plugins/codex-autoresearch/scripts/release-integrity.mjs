export function parseSha256Manifest(text, expectedFileName) {
  const manifest = String(text || "");
  if (manifest.length > 128 * 1024) {
    throw new Error(`Checksum manifest for ${expectedFileName} is too large.`);
  }

  const entries = [];
  for (const rawLine of manifest.split("\n")) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    if (line.length > 16 * 1024) {
      throw new Error(
        `Checksum manifest for ${expectedFileName} contains a line that is too long.`,
      );
    }

    const entry = parseCoreutilsLine(line) || parseOpenSslLine(line);
    if (!entry) {
      throw new Error(
        `Checksum manifest for ${expectedFileName} must contain a SHA-256 entry generated by sha256sum.`,
      );
    }
    entries.push(entry);
  }

  if (entries.length !== 1) {
    throw new Error(
      `Checksum manifest for ${expectedFileName} must contain exactly one asset entry; found ${entries.length}.`,
    );
  }

  const entry = entries[0];
  if (entry.fileName !== expectedFileName) {
    throw new Error(`Checksum manifest expected asset ${expectedFileName}, got ${entry.fileName}.`);
  }
  return entry.hash;
}

function parseCoreutilsLine(line) {
  const hash = line.slice(0, 64);
  if (!isSha256Hex(hash) || !isManifestWhitespace(line[64])) return null;

  let index = 65;
  while (index < line.length && isManifestWhitespace(line[index])) index += 1;
  if (index >= line.length) return null;

  let fileName = line.slice(index).trim();
  if (fileName.startsWith("*")) fileName = fileName.slice(1).trimStart();
  return { hash: hash.toLowerCase(), fileName };
}

function parseOpenSslLine(line) {
  if (line.slice(0, 6).toLowerCase() !== "sha256") return null;

  let index = 6;
  while (index < line.length && isManifestWhitespace(line[index])) index += 1;
  if (line[index] !== "(") return null;

  const closeParen = line.indexOf(")", index + 1);
  if (closeParen <= index + 1) return null;

  const fileName = line.slice(index + 1, closeParen).trim();
  index = closeParen + 1;
  while (index < line.length && isManifestWhitespace(line[index])) index += 1;
  if (line[index] !== "=") return null;

  index += 1;
  while (index < line.length && isManifestWhitespace(line[index])) index += 1;
  const hash = line.slice(index);
  if (!isSha256Hex(hash)) return null;
  return { hash: hash.toLowerCase(), fileName };
}

function isSha256Hex(value) {
  if (value.length !== 64) return false;
  for (let index = 0; index < value.length; index += 1) {
    const code = value.charCodeAt(index);
    const digit = code >= 48 && code <= 57;
    const upperHex = code >= 65 && code <= 70;
    const lowerHex = code >= 97 && code <= 102;
    if (!digit && !upperHex && !lowerHex) return false;
  }
  return true;
}

function isManifestWhitespace(value) {
  return value === " " || value === "\t" || value === "\v" || value === "\f";
}
